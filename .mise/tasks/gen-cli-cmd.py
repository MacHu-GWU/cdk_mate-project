# -*- coding: utf-8 -*-

"""
Generate ``cdk_mate/cli/cli_cmd.py`` from the option registry of the installed CDK CLI.

The aws-cdk npm package ships ``lib/cli/cli-type-registry.json``: every command
and option of the CLI, with its type, description, choices and default. This
script turns it into one dataclass per command, one field per option.

Run ``mise run gen-cli-cmd`` after changing ``npm:aws-cdk`` in ``mise.toml``,
then review ``git diff cdk_mate/cli/cli_cmd.py``: it shows exactly which
options the new CLI added, changed, or removed.

Every human decision lives in the tables below. A command the registry has but
no table mentions stops the script, so a new CLI command is never skipped
silently.
"""

import json
import keyword
import shutil
import sys
from pathlib import Path

dir_project_root = Path(__file__).absolute().parent.parent.parent
path_cli_cmd = dir_project_root / "cdk_mate" / "cli" / "cli_cmd.py"

#: CLI command -> (class name, slug of its AWS docs page ``ref-cli-cmd-<slug>.html`` or None).
COMMANDS = {
    "acknowledge": ("Acknowledge", "ack"),
    "bootstrap": ("Bootstrap", "bootstrap"),
    "cli-telemetry": ("CliTelemetry", None),
    "context": ("Context", "context"),
    "deploy": ("Deploy", "deploy"),
    "destroy": ("Destroy", "destroy"),
    "diagnose": ("Diagnose", None),
    "diff": ("Diff", "diff"),
    "doctor": ("Doctor", "doctor"),
    "drift": ("Drift", "drift"),
    "flags": ("Flags", "flags"),
    "gc": ("GC", "gc"),
    "import": ("Import", "import"),
    "init": ("Init", "init"),
    "list": ("List", "list"),
    "metadata": ("Metadata", "metadata"),
    "migrate": ("Migrate", None),
    "notices": ("Notices", "notices"),
    "orphan": ("Orphan", "orphan"),
    "publish-assets": ("PublishAssets", "publish-assets"),
    "refactor": ("Refactor", "refactor"),
    "rollback": ("Rollback", "rollback"),
    "synth": ("Synth", "synth"),
    "validate": ("Validate", None),
    "watch": ("Watch", "watch"),
}

#: CLI commands that get no class, and why.
SKIPPED_COMMANDS = {
    "docs": "opens the reference documentation in a browser",
    "lsp": "a long-running language server for editors",
}

#: Extra docstring paragraphs, by CLI command.
NOTES = {
    "gc": 'This command is still in development and requires the ``--unstable=gc``\n    option, so pass ``unstable=["gc"]``.',
}

#: Field name of the positional argument, by CLI command, when it differs from
#: the lower-cased registry name. These keep the field names of cdk_mate 0.1.x.
POSITIONAL_NAMES = {
    "acknowledge": "notice_id",
    "bootstrap": "aws_environment",
    "flags": "flag_names",
    "gc": "aws_environment",
    "import": "stacks",
    "init": "template_type",
}

#: Field name of an option, by (CLI command, option), when the rule
#: (``-`` -> ``_``, a trailing ``_`` after a Python keyword) is not enough.
FIELD_NAMES = {
    ("init", "list"): "list_",  # do not shadow the builtin
}

#: Array options whose items are ``KEY=VALUE``: exposed as ``dict[str, str]``.
KEY_VALUE_OPTIONS = {"context", "parameters", "tags"}

#: Global options yargs adds by itself, so they are not in the registry.
BUILTIN_GLOBAL_OPTIONS = {
    "help": "Show help.",
    "version": "Show version number.",
}

HEADER = '''# -*- coding: utf-8 -*-

"""
AWS CDK CLI Command Wrapper Classes

One dataclass per CDK CLI command, one field per option. An option left at
``OPT`` (the default) is not passed, so the CLI uses its own default.

.. code-block:: python

    # Deploy a stack with options
    Deploy(
        stacks=["MyStack"],
        profile="my_aws_profile",
        require_approval="never",
    ).run()

    # Destroy a stack with confirmation bypass
    Destroy(
        stacks=["MyStack"],
        force=True,
    ).run()
"""

# Generated by ``mise run gen-cli-cmd`` (.mise/tasks/gen-cli-cmd.py) from the
# option registry of aws-cdk CLI {cli_version}. Do not edit by hand: change the
# generator instead. The behavior of the commands is in cli_cmd_base.py.

from __future__ import annotations

import typing as T
import dataclasses

from func_args.api import OPT
from func_args.api import BaseModel

from .cli_utils import pos_arg
from .cli_utils import value_arg
from .cli_utils import bool_arg
from .cli_utils import kv_arg
from .cli_utils import array_arg
from .cli_utils import count_arg
from .cli_cmd_base import BaseCommandMixin


@dataclasses.dataclass
class BaseCommand(BaseCommandMixin, BaseModel):
    """
    Base class for all CDK CLI commands. Its fields are the global options,
    which every command accepts.

    Two fields are not CDK options; they control how the command line is built:

    - ``cdk_cmd``: the executable, ``["cdk"]`` by default. Use it to pin a CLI
      version per project, such as ``["npx", "aws-cdk@2.1145.0"]``.
    - ``extra_args``: arguments appended verbatim at the end, for any option
      this library does not define yet, such as ``["--tags", "team=data"]``.
      An option the installed CLI does not know is ignored by the CLI with a
      warning (exit code 0), so check that your CLI version supports it.

    A boolean option passes ``--name`` for ``True`` and ``--no-name`` for
    ``False``.
    """

    # fmt: off
    cdk_cmd: list[str] = dataclasses.field(default=OPT)  #: The executable that runs the subcommand; ``["cdk"]`` when not set.
    extra_args: list[str] = dataclasses.field(default=OPT)  #: Arguments appended verbatim at the end of the command line.
'''


def find_registry() -> Path:
    """
    Locate ``cli-type-registry.json`` of the ``cdk`` executable on ``PATH``.
    """
    cdk = shutil.which("cdk")
    if cdk is None:
        sys.exit("cdk is not on PATH; run this through mise (mise run gen-cli-cmd)")
    # <prefix>/bin/cdk -> <prefix>/lib/node_modules/aws-cdk/bin/cdk
    dir_package = Path(cdk).resolve().parent.parent
    path_registry = dir_package / "lib" / "cli" / "cli-type-registry.json"
    if not path_registry.exists():
        sys.exit(f"cannot find {path_registry}")
    return path_registry


def field_name(command: str, option: str) -> str:
    if (command, option) in FIELD_NAMES:
        return FIELD_NAMES[(command, option)]
    name = option.replace("-", "_")
    if keyword.iskeyword(name):
        name = f"{name}_"
    return name


def one_line(text: str) -> str:
    return " ".join(text.split())


def rst_text(text: str) -> str:
    """
    Make CLI help text safe as reStructuredText in a ``#:`` comment or a
    docstring: ``*``, backticks, and ``|`` would start markup.
    """
    text = one_line(text).replace("\\", "\\\\")
    for char in "*`|":
        text = text.replace(char, f"\\{char}")
    return text


def option_field(command: str, option: str, spec: dict) -> str:
    """
    Render one option as a one-line dataclass field with a ``#:`` comment.
    """
    name = field_name(command, option)
    kind = spec["type"]
    if spec.get("count"):
        type_hint, arg = "int", "count_arg"
    elif kind == "boolean":
        type_hint, arg = "bool", "bool_arg"
    elif kind == "number":
        type_hint, arg = "int", "value_arg"
    elif kind == "array" and option in KEY_VALUE_OPTIONS:
        type_hint, arg = "dict[str, str]", "kv_arg"
    elif kind == "array":
        type_hint, arg = "list[str]", "array_arg"
    elif kind == "string" and "choices" in spec:
        choices = ", ".join(json.dumps(choice) for choice in spec["choices"])
        type_hint, arg = f"T.Literal[{choices}]", "value_arg"
    elif kind == "string":
        type_hint, arg = "str", "value_arg"
    else:
        sys.exit(f"unknown option type {kind!r} of {command} --{option}")

    comment = rst_text(spec.get("desc", "")).rstrip(".")
    deprecated = spec.get("deprecated")
    if deprecated is True:
        comment = f"Deprecated. {comment}"
    elif deprecated:
        comment = f"Deprecated, {rst_text(deprecated)}. {comment}"
    default = spec.get("default")
    if default not in (None, [], {}):
        comment = f"{comment} (CLI default: {json.dumps(default)})"
    return f'    {name}: {type_hint} = dataclasses.field(default=OPT, metadata={{"t": {arg}}})  #: {comment}.'


def positional_field(command: str, arg_spec: dict) -> str:
    name = POSITIONAL_NAMES.get(command, arg_spec["name"].lower())
    type_hint = "list[str]" if arg_spec.get("variadic") else "str"
    label = arg_spec["name"]
    return f'    {name}: {type_hint} = dataclasses.field(default=OPT, metadata={{"t": pos_arg}})  #: The ``{label}`` positional argument.'


def render(registry: dict, cli_version: str) -> str:
    unknown = set(registry["commands"]) - set(COMMANDS) - set(SKIPPED_COMMANDS)
    if unknown:
        sys.exit(
            f"new CLI command(s) {sorted(unknown)}: add them to COMMANDS or SKIPPED_COMMANDS"
        )
    gone = set(COMMANDS) - set(registry["commands"])
    if gone:
        sys.exit(
            f"CLI command(s) {sorted(gone)} no longer exist: decide how to deprecate their classes"
        )

    lines = [HEADER.replace("{cli_version}", cli_version).rstrip("\n")]
    global_options = dict(registry["globalOptions"])
    for option, desc in BUILTIN_GLOBAL_OPTIONS.items():
        global_options[option] = {"type": "boolean", "desc": desc}
    for option in sorted(global_options):
        lines.append(option_field("", option, global_options[option]))
    lines.append("    # fmt: on")

    for command in sorted(COMMANDS, key=lambda c: COMMANDS[c][0]):
        class_name, slug = COMMANDS[command]
        spec = registry["commands"][command]
        doc = [rst_text(spec["description"]).rstrip(".") + "."]
        if command in NOTES:
            doc.append(NOTES[command])
        if slug is not None:
            doc.append(
                f"Ref: https://docs.aws.amazon.com/cdk/v2/guide/ref-cli-cmd-{slug}.html"
            )
        else:
            doc.append(f"Ref: ``cdk {command} --help``")
        lines.append("")
        lines.append("")
        lines.append("@dataclasses.dataclass")
        lines.append(f"class {class_name}(BaseCommand):")
        body = "\n\n".join(f"    {paragraph}" for paragraph in doc)
        # rst_text() escapes with backslashes; a raw docstring keeps them valid Python
        prefix = "r" if "\\" in body else ""
        lines.append(f'    {prefix}"""')
        lines.append(body)
        lines.append('    """')
        fields = []
        if spec.get("arg"):
            fields.append(positional_field(command, spec["arg"]))
        options = spec.get("options", {})
        for option in sorted(options):
            fields.append(option_field(command, option, options[option]))
        if fields:
            lines.append("")
            lines.append("    # fmt: off")
            lines.extend(fields)
            lines.append("    # fmt: on")
        lines.append("")
        lines.append("    def _subcommand(self) -> list[str]:")
        lines.append(f'        return ["{command}"]')
    return "\n".join(lines) + "\n"


def main():
    path_registry = find_registry()
    registry = json.loads(path_registry.read_text())
    path_package_json = path_registry.parent.parent.parent / "package.json"
    cli_version = json.loads(path_package_json.read_text())["version"]
    path_cli_cmd.write_text(render(registry, cli_version))
    print(f"Generated {path_cli_cmd} from aws-cdk CLI {cli_version}")


if __name__ == "__main__":
    main()
